def rec(s, n, date, km, hrs, typ, title, **kw):
    r = {'record_id': f'H-{s}-{n:03d}', 'date': date, 'mileage_km': km, 'operating_hours': hrs, 'type': typ, 'title': title,
         'complaint': None, 'dtcs': [], 'findings': [], 'measurements': [], 'works': [], 'parts': [],
         'mechanic': MECH[VEH[s]['mech']]['name'], 'result': None, 'follow_up': None}
    r.update(kw)
    r['labor_hours_actual'] = round(sum(w['actual_hours'] for w in r['works']), 2)
    return r
